        --     intensity = 0.15,
        --     color     = { 0.4, 0.35, 0.3 },
        -- },
    },

    -- Опции
    tiling    = true,       -- бесшовное тайлинг (рекомендуется для полов/стен)
    normal_map = false,     -- генерировать карту нормалей (для 3D)
    roughness  = 0.7,       -- шероховатость (0=зеркало, 1=матовый)
})

