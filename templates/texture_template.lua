            -- color = { 0.8, 0.7, 0.6 },
            -- blend = "overlay",   -- "mix" | "overlay" | "add"
        },

        -- Слой Вороного (многоугольные клетки, трещины)
        {
            type       = "voronoi",
            scale      = 6.0,
            edge_width = 0.05,      -- ширина краёв (трещин)
            edge_color = { 0.2, 0.15, 0.1 },
        },

        -- Клеточный шум (Уорли, органические пятна)
        -- {
