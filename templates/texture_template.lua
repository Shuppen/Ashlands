register_texture("my_texture", {
    -- Размер текстуры (рекомендуется 16, 32 или 64)
    size = 32,

    -- Базовый цвет (RGB, значения 0..1)
    base_color = { 0.5, 0.5, 0.5 },

    -- Слои накладываются сверху вниз
    layers = {
        -- Слой шума Перлина (плавные органические переходы)
        {
            type      = "perlin",
            scale     = 4.0,        -- масштаб узора (больше = крупнее)
            intensity = 0.3,        -- сила эффекта (0..1)
            -- Изменение цвета (отклонение от базового)
            color_var = { 0.05, 0.05, 0.03 },
